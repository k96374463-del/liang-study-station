function toggleChapterCard(button) {
  const card = button.closest(".chapter-card");
  const shouldOpen = !card.classList.contains("is-open");
  document.querySelectorAll(".chapter-card").forEach((item) => {
    if (item !== card) closeChapter(item);
  });
  if (shouldOpen) openChapterCard(card);
  else closeChapter(card);
}

