function answerQuestion(selectedIndex) {
  if (!quiz || quiz.answered) return;
  const question = questions.find((item) => item.id === quiz.ids[quiz.index]);
  const isCorrect = selectedIndex === question.answer;
  quiz.answered = true;

  document.querySelectorAll(".option-button").forEach((button, index) => {
    button.disabled = true;
    if (index === question.answer) button.classList.add("is-correct");
    if (index === selectedIndex && !isCorrect) button.classList.add("is-wrong");
  });

  state.answered += 1;
  if (isCorrect) {
    quiz.correct += 1;
    quiz.score += 4;
    state.correct += 1;
    state.wrongIds = state.wrongIds.filter((id) => id !== question.id);
  } else {
    quiz.wrong.push(question.id);
    if (!state.wrongIds.includes(question.id)) state.wrongIds.push(question.id);
  }
  recordLearning("question", question.prompt, question.chapter, isCorrect ? "correct" : "wrong");
  saveState();

  const feedback = document.getElementById("answer-feedback");
  feedback.hidden = false;
  feedback.classList.toggle("is-wrong", !isCorrect);
  document.getElementById("feedback-title").textContent = isCorrect ? "答对了" : "这道题记入错题簿";
  document.getElementById("feedback-text").textContent = question.explanation;
  document.getElementById("next-question").disabled = false;
  document.getElementById("quiz-score").textContent = quiz.score;
  document.getElementById("quiz-progress-bar").style.width =
    `${((quiz.index + 1) / quiz.ids.length) * 100}%`;
  updateProgressUI();
}

