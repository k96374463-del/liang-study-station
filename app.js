function compressImageFile(file) {
  return new Promise((resolve, reject) => {
    if (!file || !file.type.startsWith("image/")) {
      reject(new Error("请选择图片文件。"));
      return;
    }
    if (file.size > 15 * 1024 * 1024) {
      reject(new Error("图片超过 15MB，请先压缩后再上传。"));
      return;
    }

    const objectUrl = URL.createObjectURL(file);
    const image = new Image();
    image.onload = () => {
      const maxSide = 1280;
      const scale = Math.min(1, maxSide / Math.max(image.naturalWidth, image.naturalHeight));
      const canvas = document.createElement("canvas");
      canvas.width = Math.max(1, Math.round(image.naturalWidth * scale));
      canvas.height = Math.max(1, Math.round(image.naturalHeight * scale));
      const context = canvas.getContext("2d");
      context.fillStyle = "#fff";
      context.fillRect(0, 0, canvas.width, canvas.height);
      context.drawImage(image, 0, 0, canvas.width, canvas.height);
      URL.revokeObjectURL(objectUrl);
      resolve(canvas.toDataURL("image/jpeg", 0.76));
    };
    image.onerror = () => {
      URL.revokeObjectURL(objectUrl);
      reject(new Error("这张图片无法读取，请换一张 JPG 或 PNG 图片。"));
    };
    image.src = objectUrl;
  });
}

async function handleEditorImage(input) {
  const prefix = input.id.replace(/-image-input$/, "");
  const file = input.files?.[0];
  if (!file) return;
  try {
    const dataUrl = await compressImageFile(file);
    document.getElementById(`${prefix}-image-data`).value = dataUrl;
    const preview = document.getElementById(`${prefix}-image-preview`);
    document.getElementById(`${prefix}-image-preview-img`).src = dataUrl;
    preview.hidden = false;
    showToast("图片已压缩并添加到当前内容。");
  } catch (error) {
    showToast(error.message || "图片处理失败，请重新选择。");
    input.value = "";
  }
}

function saveCustomQuestion(form) {
  const editId = form.dataset.editId;
  const image = document.getElementById("custom-question-image-data").value;
  const promptValue = document.getElementById("custom-question-prompt").value.trim();
  const options = [0, 1, 2, 3].map(
    (index) => document.getElementById(`custom-option-${index}`).value.trim()
  );
  if (!promptValue && !image) {
    showToast("请至少输入题目文字或上传一张题目图片。");
    return;
  }
  if (options.some((option) => !option)) {
    showToast("请填写全部四个选项。");
    return;
  }

  const id = editId || `custom-q-${Date.now()}`;
  const item = {
    id,
    chapter: Number(document.getElementById("custom-question-chapter").value),
    prompt: promptValue || "请根据图片作答",
    image,
    options,
    answer: Number(document.getElementById("custom-question-answer").value),
    explanation:
      document.getElementById("custom-question-explanation").value.trim() ||
      "这道题由你自定义添加。",
    isCustom: true
  };

  if (editId) {
    state.customQuestions = state.customQuestions.map((question) =>
      question.id === editId ? item : question
    );
  } else {
    state.customQuestions.push(item);
  }
  if (document.getElementById("custom-question-wrong").checked && !state.wrongIds.includes(id)) {
    state.wrongIds.push(id);
  }
  hydrateCustomContent();
  saveState();
  if (quiz) exitQuiz();
  closeCustomDialog();
  renderQuizSetup();
  updateProgressUI();
  renderWrongBook();
  showToast(editId ? "题目已更新。" : "题目已加入题库。");
}

