function normalizeSettings() {
  const savedSettings =
    state.settings && typeof state.settings === "object" ? state.settings : {};
  const timerMinutes = Number(savedSettings.defaultTimerMinutes);
  state.settings = {
    ...defaultState.settings,
    ...savedSettings,
    defaultTimerMinutes: Number.isFinite(timerMinutes)
      ? Math.min(180, Math.max(1, Math.round(timerMinutes)))
      : 25,
    reduceMotion: Boolean(savedSettings.reduceMotion),
    lastBackupAt:
      typeof savedSettings.lastBackupAt === "string"
        ? savedSettings.lastBackupAt
        : null
  };
}

function applyMotionPreference() {
  normalizeSettings();
  document.body.classList.toggle("reduce-motion", state.settings.reduceMotion);
}

function readStoredJson(key, fallback = {}) {
  try {
    const saved = JSON.parse(localStorage.getItem(key) || "null");
    return saved && typeof saved === "object" ? saved : fallback;
  } catch {
    return fallback;
  }
}

function createBackupPayload() {
  normalizeSettings();
  return {
    format: "liang-study-station-backup",
    version: 1,
    exportedAt: new Date().toISOString(),
    app: readStoredJson(STORAGE_KEY, state),
    english: readStoredJson(ENGLISH_STORAGE_KEY, {
      mastered: [],
      readExams: []
    })
  };
}

function formatSettingsTime(value) {
  if (!value) return "还没有生成过备份";
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return "还没有生成过备份";
  return `最近备份：${new Intl.DateTimeFormat("zh-CN", {
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
    hour: "2-digit",
    minute: "2-digit"
  }).format(date)}`;
}

function renderSettings() {
  normalizeSettings();
  const timerInput = document.getElementById("settings-timer-minutes");
  if (!timerInput) return;

  ensureStudyTimer();
  const currentMinutes = Math.round(state.studyTimer.duration / 60);
  if (document.activeElement !== timerInput) {
    timerInput.value = String(currentMinutes);
  }
  document.querySelectorAll("[data-settings-timer-preset]").forEach((button) => {
    button.classList.toggle(
      "is-selected",
      Number(button.dataset.settingsTimerPreset) === currentMinutes
    );
  });
  document.querySelectorAll("#view-settings [data-study-status]").forEach((button) => {
    button.classList.toggle(
      "is-active",
      button.dataset.studyStatus === state.studyStatus
    );
  });

  const motionToggle = document.getElementById("settings-reduce-motion");
  if (motionToggle) motionToggle.checked = state.settings.reduceMotion;
  const artAnswered = document.getElementById("settings-art-answered");
  if (artAnswered) artAnswered.textContent = String(state.answered);
  const artKnown = document.getElementById("settings-art-known");
  if (artKnown) {
    artKnown.textContent = `${state.knownCards.length + state.foreignKnownCards.length}`;
  }

  const englishStats = window.EnglishStudy?.getStats?.();
  const englishMastered = document.getElementById("settings-english-mastered");
  if (englishMastered) {
    englishMastered.textContent = englishStats
      ? englishStats.mastered.toLocaleString("zh-CN")
      : "0";
  }
  const englishExams = document.getElementById("settings-english-exams");
  if (englishExams) {
    englishExams.textContent = englishStats
      ? `${englishStats.readExams} / ${englishStats.totalExams}`
      : "0 / 0";
  }

  const backupText = JSON.stringify(createBackupPayload(), null, 2);
  const backupSize = document.getElementById("settings-backup-size");
  if (backupSize) {
    const size = new Blob([backupText]).size;
    backupSize.textContent =
      size >= 1024 * 1024
        ? `${(size / 1024 / 1024).toFixed(1)} MB`
        : `${Math.max(1, Math.round(size / 1024))} KB`;
  }
  const backupNote = document.getElementById("settings-backup-note");
  if (backupNote) {
    backupNote.textContent = formatSettingsTime(state.settings.lastBackupAt);
  }
  applyMotionPreference();
}

