function saveKnowledgeMaterial(form) {
  const editId = form.dataset.editId;
  const title = document.getElementById("knowledge-title").value.trim();
  const content = document.getElementById("knowledge-content").value.trim();
  const subject = document.getElementById("knowledge-subject").value;
  if (!title || !content) {
    showToast("请填写资料标题和知识正文。");
    return;
  }
  const existing = editId
    ? state.customMaterials.find((material) => material.id === editId)
    : null;
  const tags = [
    ...new Set(
      document
        .getElementById("knowledge-tags")
        .value.split(/[,，;；\s]+/)
        .map((tag) => tag.trim())
        .filter(Boolean)
    )
  ].slice(0, 10);
  const now = new Date().toISOString();
  const item = {
    id: editId || `knowledge-${Date.now()}`,
    title,
    subject: knowledgeSubjectOptions[subject] ? subject : "other",
    chapter: document.getElementById("knowledge-chapter").value.trim(),
    tags,
    content,
    source: document.getElementById("knowledge-source").value.trim(),
    image: document.getElementById("knowledge-material-image-data").value,
    createdAt: existing?.createdAt || now,
    updatedAt: now
  };

  if (editId) {
    state.customMaterials = state.customMaterials.map((material) =>
      material.id === editId ? item : material
    );
  } else {
    state.customMaterials.unshift(item);
  }
  saveState();
  closeCustomDialog();
  renderKnowledgeBase();
  renderProfile();
  updateProgressUI();
  showToast(editId ? "学习资料已更新。" : "学习资料已加入知识库。");
}

