function createTodayTodo(text = "", done = false) {
  return {
    id: `todo-${Date.now()}-${Math.random().toString(16).slice(2)}`,
    text,
    done
  };
}

function ensureTodayTodos() {
  const today = getLocalDateKey();
  if (
    !state.todayTodos ||
    state.todayTodos.date !== today ||
    !Array.isArray(state.todayTodos.items)
  ) {
    state.todayTodos = { date: today, items: [createTodayTodo()] };
  }
  if (!state.todayTodos.items.length) {
    state.todayTodos.items.push(createTodayTodo());
  }
}

function scheduleTodayTodosSave() {
  window.clearTimeout(todoSaveTimer);
  todoSaveTimer = window.setTimeout(() => saveState(), 220);
}

function renderTodayTodos(focusId = null) {
  ensureTodayTodos();
  const list = document.getElementById("today-custom-list");
  const summary = document.getElementById("today-custom-summary");
  if (!list || !summary) return;

  const filled = state.todayTodos.items.filter((item) => item.text.trim());
  const done = filled.filter((item) => item.done).length;
  summary.textContent = filled.length ? `${done} / ${filled.length} 项` : "0 项";

  list.innerHTML = state.todayTodos.items
    .map(
      (item, index) => `
        <div class="today-custom-row ${item.done ? "is-done" : ""}" data-todo-row="${item.id}">
          <label class="today-todo-check" aria-label="标记为完成">
            <input type="checkbox" data-todo-toggle="${item.id}" ${item.done ? "checked" : ""}>
            <span aria-hidden="true"></span>
          </label>
          <input class="today-custom-input" type="text" data-todo-input="${item.id}" value="${escapeHtml(item.text)}" placeholder="${index === 0 ? "写下今天要做的事" : "继续添加一项"}">
          <button class="today-todo-remove" type="button" data-todo-remove="${item.id}" aria-label="删除这条今日事项"><span aria-hidden="true"></span></button>
          ${
            index === state.todayTodos.items.length - 1
              ? `<button class="today-todo-add" type="button" data-todo-add aria-label="添加今日事项"><span aria-hidden="true"></span></button>`
              : `<span class="today-todo-slot" aria-hidden="true"></span>`
          }
        </div>
      `
    )
    .join("");

  if (focusId) {
    window.requestAnimationFrame(() => {
      document.querySelector(`[data-todo-input="${focusId}"]`)?.focus();
    });
  }
}

function addTodayTodo() {
  ensureTodayTodos();
  const item = createTodayTodo();
  state.todayTodos.items.push(item);
  saveState();
  renderTodayTodos(item.id);
}

function removeTodayTodo(id) {
  ensureTodayTodos();
  if (state.todayTodos.items.length === 1) {
    state.todayTodos.items[0] = createTodayTodo();
  } else {
    state.todayTodos.items = state.todayTodos.items.filter((item) => item.id !== id);
  }
  saveState();
  renderTodayTodos();
}

function ensureStudyTimer() {
  if (
    !state.studyTimer ||
    !Number.isFinite(state.studyTimer.remaining) ||
    !Number.isFinite(state.studyTimer.duration)
  ) {
    state.studyTimer = {
      duration: STUDY_DURATION_SECONDS,
      remaining: STUDY_DURATION_SECONDS,
      running: false,
      endsAt: null,
      completed: false,
      celebrated: false
    };
  }
  if (typeof state.studyTimer.celebrated !== "boolean") {
    state.studyTimer.celebrated = false;
  }

  if (state.studyTimer.running && state.studyTimer.endsAt) {
    state.studyTimer.remaining = Math.max(
      0,
      Math.ceil((state.studyTimer.endsAt - Date.now()) / 1000)
    );
    if (state.studyTimer.remaining === 0) {
      state.studyTimer.running = false;
      state.studyTimer.endsAt = null;
      state.studyTimer.completed = true;
    }
  }
}

function formatStudyTime(totalSeconds) {
  const seconds = Math.max(0, Math.ceil(totalSeconds));
  const minutes = Math.floor(seconds / 60);
  const remainder = seconds % 60;
  return `${String(minutes).padStart(2, "0")}:${String(remainder).padStart(2, "0")}`;
}

function renderStudyTimer() {
  ensureStudyTimer();
  const panel = document.getElementById("study-timer");
  const display = document.getElementById("study-timer-time");
  const button = document.getElementById("study-timer-button");
  if (!panel || !display || !button) return;

  display.textContent = formatStudyTime(state.studyTimer.remaining);
  panel.classList.toggle("is-running", state.studyTimer.running);
  panel.classList.toggle("is-complete", state.studyTimer.completed);
  button.textContent = state.studyTimer.running
    ? "暂停"
    : state.studyTimer.remaining <= 0
      ? "重新开始"
      : state.studyTimer.remaining < state.studyTimer.duration
        ? "继续学习"
        : "开始学习";
  button.setAttribute(
    "aria-label",
    state.studyTimer.running
      ? `暂停学习倒计时，剩余 ${formatStudyTime(state.studyTimer.remaining)}`
      : `${button.textContent}，倒计时 ${formatStudyTime(state.studyTimer.remaining)}`
  );
  const minutesInput = document.getElementById("study-timer-minutes");
  if (minutesInput && document.activeElement !== minutesInput) {
    minutesInput.value = String(Math.round(state.studyTimer.duration / 60));
  }
}

function stopStudyTimerTicker() {
  if (studyTimerInterval) {
    window.clearInterval(studyTimerInterval);
    studyTimerInterval = null;
  }
}

function startStudyTimerTicker() {
  stopStudyTimerTicker();
  if (!state.studyTimer.running) return;
  studyTimerInterval = window.setInterval(() => {
    ensureStudyTimer();
    if (state.studyTimer.remaining <= 0) {
      stopStudyTimerTicker();
      saveState();
      renderStudyTimer();
      playStudyCelebrationOnce();
      return;
    }
    renderStudyTimer();
  }, 1000);
}

function toggleStudyTimer() {
  ensureStudyTimer();
  closeStudyTimerSettings();
  if (state.studyTimer.running) {
    state.studyTimer.remaining = Math.max(
      0,
      Math.ceil((state.studyTimer.endsAt - Date.now()) / 1000)
    );
    state.studyTimer.running = false;
    state.studyTimer.endsAt = null;
    stopStudyTimerTicker();
    saveState();
    renderStudyTimer();
    return;
  }

  if (state.studyTimer.remaining <= 0) {
    state.studyTimer.remaining = state.studyTimer.duration || STUDY_DURATION_SECONDS;
  }
  state.studyTimer.running = true;
  state.studyTimer.completed = false;
  state.studyTimer.celebrated = false;
  state.studyTimer.endsAt = Date.now() + state.studyTimer.remaining * 1000;
  saveState();
  renderStudyTimer();
  startStudyTimerTicker();
}

function setStudyTimerDuration(minutes) {
  const safeMinutes = Math.min(180, Math.max(1, Math.round(Number(minutes))));
  if (!Number.isFinite(safeMinutes)) {
    showToast("请输入 1–180 分钟。");
    return;
  }
  const seconds = safeMinutes * 60;
  stopStudyTimerTicker();
  state.studyTimer = {
    duration: seconds,
    remaining: seconds,
    running: false,
    endsAt: null,
    completed: false,
    celebrated: false
  };
  normalizeSettings();
  state.settings.defaultTimerMinutes = safeMinutes;
  saveState();
  closeStudyTimerSettings();
  renderStudyTimer();
  renderSettings();
  showToast(`学习倒计时已设为 ${safeMinutes} 分钟。`);
}

function openStudyTimerSettings() {
  ensureStudyTimer();
  if (state.studyTimer.running) {
    showToast("请先暂停倒计时，再修改时长。");
    return;
  }
  const settings = document.getElementById("study-timer-settings");
  const minutesInput = document.getElementById("study-timer-minutes");
  minutesInput.value = String(Math.round(state.studyTimer.duration / 60));
  settings.hidden = false;
  document.getElementById("study-timer-time").setAttribute("aria-expanded", "true");
  minutesInput.focus();
  minutesInput.select();
}

function closeStudyTimerSettings() {
  const settings = document.getElementById("study-timer-settings");
  settings.hidden = true;
  document.getElementById("study-timer-time").setAttribute("aria-expanded", "false");
}

function playStudyCelebrationOnce() {
  ensureStudyTimer();
  if (!state.studyTimer.completed || state.studyTimer.celebrated) return;
  state.studyTimer.celebrated = true;
  saveState();

  const panel = document.getElementById("study-celebration");
  const image = document.getElementById("study-celebration-image");
  const photos = ["assets/timer-boy-1.png", "assets/timer-boy-2.png"];
  const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  window.clearTimeout(celebrationTimeout);
  panel.hidden = false;
  panel.classList.add("is-visible");

  if (reduceMotion) {
    image.src = photos[1];
    celebrationTimeout = window.setTimeout(() => {
      panel.classList.remove("is-visible");
      panel.hidden = true;
    }, 1800);
    return;
  }

  const sequence = [0, 1, 0, 1];
  sequence.forEach((photoIndex, frameIndex) => {
    window.setTimeout(() => {
      image.src = photos[photoIndex];
      image.classList.remove("is-changing");
      void image.offsetWidth;
      image.classList.add("is-changing");
      if (frameIndex === sequence.length - 1) {
        celebrationTimeout = window.setTimeout(() => {
          panel.classList.remove("is-visible");
          panel.hidden = true;
        }, 650);
      }
    }, frameIndex * 650);
  });
}

