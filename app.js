function renderKnowledgeBase() {
  const grid = document.getElementById("knowledge-grid");
  const empty = document.getElementById("knowledge-empty");
  const filters = document.getElementById("knowledge-filters");
  if (!grid || !empty || !filters) return;

  const subjectFilters = [
    { id: "all", label: "全部资料" },
    ...Object.entries(knowledgeSubjectOptions).map(([id, label]) => ({ id, label }))
  ];
  filters.innerHTML = subjectFilters
    .map(
      (filter) => `
        <button class="filter-chip ${knowledgeSubjectFilter === filter.id ? "is-active" : ""}" type="button" data-knowledge-filter="${filter.id}">
          ${filter.label}
        </button>
      `
    )
    .join("");

  const search = knowledgeSearch.trim().toLowerCase();
  const visible = [...state.customMaterials]
    .filter(
      (material) =>
        knowledgeSubjectFilter === "all" || material.subject === knowledgeSubjectFilter
    )
    .filter((material) => {
      if (!search) return true;
      return [
        material.title,
        material.chapter,
        material.content,
        material.source,
        ...(material.tags || [])
      ]
        .join(" ")
        .toLowerCase()
        .includes(search);
    })
    .sort((left, right) => {
      const leftTime = new Date(left.updatedAt || left.createdAt || 0).getTime();
      const rightTime = new Date(right.updatedAt || right.createdAt || 0).getTime();
      return rightTime - leftTime;
    });

  document.getElementById("knowledge-total-count").textContent =
    state.customMaterials.length;
  document.getElementById("knowledge-visible-count").textContent = visible.length;
  const sidebarCount = document.getElementById("sidebar-knowledge-count");
  if (sidebarCount) sidebarCount.textContent = state.customMaterials.length;

  const isEmpty = visible.length === 0;
  grid.hidden = isEmpty;
  empty.hidden = !isEmpty;
  document.getElementById("knowledge-empty-title").textContent =
    state.customMaterials.length === 0 ? "知识库还是空的" : "没有找到对应资料";
  document.getElementById("knowledge-empty-copy").textContent =
    state.customMaterials.length === 0
      ? "添加第一条学习资料，建立属于自己的知识库。"
      : "换一个关键词，或选择其他板块后再试。";
  const emptyAction = document.getElementById("knowledge-empty-action");
  emptyAction.textContent =
    state.customMaterials.length === 0 ? "添加学习资料" : "添加新资料";

  grid.innerHTML = visible
    .map((material) => {
      const tags = Array.isArray(material.tags) ? material.tags : [];
      const updated = new Date(material.updatedAt || material.createdAt || Date.now());
      return `
        <article class="knowledge-card knowledge-${material.subject || "other"}" data-knowledge-id="${escapeHtml(material.id)}">
          <div class="knowledge-card-top">
            <span class="knowledge-subject">${knowledgeSubjectOptions[material.subject] || "其他主题"}</span>
            <time datetime="${updated.toISOString()}">${updated.toLocaleDateString("zh-CN")}</time>
          </div>
          <h2>${escapeHtml(material.title)}</h2>
          ${material.chapter ? `<p class="knowledge-topic">${escapeHtml(material.chapter)}</p>` : ""}
          ${material.image ? `<img class="knowledge-image" src="${escapeHtml(material.image)}" alt="">` : ""}
          <p class="knowledge-body">${escapeHtml(material.content)}</p>
          ${
            tags.length
              ? `<div class="knowledge-tags">${tags.map((tag) => `<span>${escapeHtml(tag)}</span>`).join("")}</div>`
              : ""
          }
          <div class="knowledge-card-foot">
            <span>${material.source ? `来源：${escapeHtml(material.source)}` : "来源：自定义整理"}</span>
            <div>
              <button type="button" data-edit-material="${escapeHtml(material.id)}">编辑</button>
              <button type="button" data-delete-material="${escapeHtml(material.id)}">删除</button>
            </div>
          </div>
        </article>
      `;
    })
    .join("");
}

