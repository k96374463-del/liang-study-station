function markCard(known) {
  const isForeign = activeReviewSubject === "foreign";
  const cards = isForeign ? foreignCards : currentCards();
  const index = isForeign ? foreignReviewCardIndex : cardIndex;
  const card = cards[index];
  if (!card) return;
  const knownKey = isForeign ? "foreignKnownCards" : "knownCards";
  if (known) {
    const wasKnown = state[knownKey].includes(card.id);
    if (!wasKnown) state[knownKey].push(card.id);
    if (!wasKnown && !isForeign) recordLearning("card", card.question, card.chapter, "known");
    showToast(isForeign ? "已记住这张外国美术史卡片。" : "已标记为掌握，继续下一张。");
  } else {
    state[knownKey] = state[knownKey].filter((id) => id !== card.id);
    showToast(isForeign ? "已放回外国美术史待复习。" : "已放回待复习，稍后会再次出现。");
  }
  saveState();
  if (isForeign) foreignReviewCardIndex += 1;
  else cardIndex += 1;
  updateProgressUI();
  renderFlashcard();
}

